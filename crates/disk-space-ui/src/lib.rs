//! Native Shell UI for `disk-space`.
//!
//! Renders the dark obsidian dot-matrix disk map, category sidebar,
//! breadcrumb item browser, `DaisyDisk` radial sunburst chart, aggregations,
//! and root-jailed destruction / secure erasure drawer.

#![forbid(unsafe_code)]

mod dot_matrix;
mod explorer;
mod keybindings;
mod palette;
mod settings_modal;
mod shell;
mod sidebar;
mod snag_drawer;
mod state;
mod sunburst;

use nsh_base::theme;
use nsh_core::prelude::IntoElement;
use nsh_core::prelude::ParentElement;
use nsh_core::prelude::Styled;
use nsh_core::prelude::component;
use nsh_core::prelude::view;

pub use state::LaunchConfig;
pub use state::configure_launch;

/// Root Native Shell component for `disk-space`.
#[component]
#[expect(
    clippy::exhaustive_structs,
    reason = "generated by nsh_macros::component"
)]
pub fn App() -> impl IntoElement {
    state::ensure_started();
    let _ = theme();

    view().flex_1().bg(palette::BG_CANVAS).child(shell::shell())
}
